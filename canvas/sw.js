self.addEventListener('install',e=>{e.waitUntil((async()=>{
  const c=await caches.open(SHELL);
  // addAll() honours the HTTP cache, which can precache STALE copies (304s).
  // Fetch with cache:'reload' so every shell file is revalidated at install time.
  for(let i=0;i<FILES.length;i+=25){
    await Promise.all(FILES.slice(i,i+25).map(async u=>{
      try{ const r=unredirect(await fetch(u,{cache:'reload'})); if(r.ok) await c.put(u,r); }catch(e){}
    }));
  }
  self.skipWaiting();
})());});

self.addEventListener('activate',e=>{e.waitUntil((async()=>{
  for(const k of await caches.keys())
    if(k!==SHELL && k!==ASSETS) await caches.delete(k);   // keep the asset cache
  await self.clients.claim();
})());});

self.addEventListener('fetch',e=>{
  if(e.request.method!=='GET') return;
  // never intercept or cache the sync API — stale scores would be worse than none
  if(new URL(e.request.url).pathname.startsWith('/api/')) return;
  // never serve the login page or gated navigations from cache — the server
  // has to decide whether this request is still authenticated
  if(new URL(e.request.url).pathname.startsWith('/login')) return;
  if(e.request.mode==='navigate') return;
  e.respondWith((async()=>{
    const isAsset=/\/assets\//.test(new URL(e.request.url).pathname);
    const box=isAsset?ASSETS:SHELL;
    const hit=await caches.match(e.request,{ignoreSearch:true});
    if(hit) return hit;
    try{
      const r=unredirect(await fetch(e.request));
      if(r.ok){ const c=await caches.open(box); c.put(e.request,r.clone()).catch(function(){}); }
      return r;
    }catch(err){
      return new Response('Offline and not cached',{status:503,headers:{'Content-Type':'text/plain'}});
    }
  })());
});
