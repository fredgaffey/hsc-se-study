/* A response with redirected=true cannot be returned for a navigation request
   (Chrome fails the navigation with a network error) and cannot be stored with
   cache.put(). Cloudflare's default html_handling 307-redirects /x.html -> /x,
   so rebuild any redirected response into a plain one. */
function unredirect(r){
  if(!r || !r.redirected) return r;
  return new Response(r.body,{status:r.status,statusText:r.statusText,headers:r.headers});
}

